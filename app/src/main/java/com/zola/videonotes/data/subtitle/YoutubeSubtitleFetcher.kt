package com.zola.videonotes.data.subtitle

import com.zola.videonotes.data.network.newpipe.NewPipeSetup
import com.zola.videonotes.domain.model.Platform
import com.zola.videonotes.domain.model.SubtitleSource
import com.zola.videonotes.domain.model.VideoInfo
import com.zola.videonotes.domain.model.storageKey
import com.zola.videonotes.domain.subtitle.SubtitleFetchResult
import com.zola.videonotes.domain.subtitle.SubtitleFetcher
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import okhttp3.OkHttpClient
import org.schabi.newpipe.extractor.NewPipe
import org.schabi.newpipe.extractor.stream.StreamInfo
import org.schabi.newpipe.extractor.stream.SubtitlesStream
import java.io.IOException
import javax.inject.Inject
import javax.inject.Singleton

/**
 * YouTube 字幕获取器（P0）：经 NewPipeExtractor 拿 timedtext 字幕轨道，下载后解析为分段。
 *
 * 选轨道策略：非自动生成 zh > 非自动生成 en > 自动生成 zh > 自动生成 en > 第一条，
 * 逐条下载解析，首条非空即用（P3 轨道级兜底链，与 B站共用同一顺序）。
 * 无字幕轨道时返回空结果（上层走 ASR 兜底），不抛异常；
 * 风控 / 网络异常时返回面向用户的中文原因。
 */
@Singleton
class YoutubeSubtitleFetcher @Inject constructor(
    private val okHttpClient: OkHttpClient,
    private val newPipeSetup: NewPipeSetup,
) : SubtitleFetcher {

    override suspend fun fetch(video: VideoInfo): Result<SubtitleFetchResult> {
        require(video.platform == Platform.YOUTUBE) { "YoutubeSubtitleFetcher 仅处理 YouTube 视频" }
        return try {
            newPipeSetup.ensureInit()
            val service = NewPipe.getService(YOUTUBE_SERVICE_ID)
            val watchUrl = "https://www.youtube.com/watch?v=${video.videoId}"
            val info = withContext(Dispatchers.IO) {
                StreamInfo.getInfo(service, watchUrl)
            }
            val tracks = info.subtitles
            if (tracks.isEmpty()) {
                // 无字幕：返回空结果，上层走 ASR 兜底
                return Result.success(SubtitleFetchResult(emptyList(), SubtitleSource.OFFICIAL, ""))
            }
            // P3：轨道级兜底链——与 B站同一顺序，逐条下载解析，首条非空即用。
            val ordered = orderSubtitleTracks(
                tracks,
                isAuto = { it.isAutoGenerated },
                langTag = { it.languageTag.orEmpty() },
            )
            val videoId = video.storageKey()
            when (val outcome = firstNonEmptyTrack(ordered) { track ->
                val contentUrl = track.content
                if (contentUrl.isBlank()) throw IOException("字幕轨道地址为空")
                val raw = okHttpClient.downloadText(contentUrl)
                val source = if (track.isAutoGenerated) SubtitleSource.AUTO else SubtitleSource.OFFICIAL
                try {
                    parseTimedtextJson3(raw, videoId, source)
                } catch (e: Exception) {
                    // json3 解析失败时降级尝试 srv3（XML）
                    parseTimedtextSrv3(raw, videoId, source)
                }
            }) {
                is TrackAttemptOutcome.Hit<*> -> {
                    val track = outcome.candidate as SubtitlesStream
                    val source = if (track.isAutoGenerated) SubtitleSource.AUTO else SubtitleSource.OFFICIAL
                    Result.success(
                        SubtitleFetchResult(
                            segments = outcome.segments,
                            source = source,
                            languageLabel = track.displayLanguageName.orEmpty(),
                        ),
                    )
                }
                is TrackAttemptOutcome.Empty ->
                    Result.success(SubtitleFetchResult(emptyList(), SubtitleSource.OFFICIAL, ""))
                is TrackAttemptOutcome.Failed ->
                    Result.failure(mapYoutubeSubtitleError(outcome.error))
            }
        } catch (e: IOException) {
            Result.failure(e)
        } catch (e: kotlinx.coroutines.CancellationException) {
            // M-19：取消必须原样抛出；吞成失败会让“用户取消”变“XX失败”，且重试逻辑误判。
            throw e
        } catch (t: Throwable) {
            Result.failure(mapYoutubeSubtitleError(t))
        }
    }

    /**
     * 字幕失败原因映射（与旧外层 catch 同口径）：
     * IOException 原样返回；非 IO 异常中含 bot / Sign in 字样时给风控友好文案，其余给通用文案。
     * （注：SSLException 是 IOException 子类，旧代码里先被 IOException 分支接住，
     * 故此处不单独列出，行为与旧代码一致。）
     */
    private fun mapYoutubeSubtitleError(t: Throwable): IOException {
        if (t is IOException) return t
        val message = t.message.orEmpty()
        return if (message.contains("bot", ignoreCase = true) ||
            message.contains("Sign in", ignoreCase = true)
        ) {
            IOException("YouTube 暂时限制了访问，可稍后重试或等待语音转写兜底")
        } else {
            IOException("YouTube 字幕获取失败：${t.message ?: t.javaClass.simpleName}")
        }
    }

    private companion object {
        /** NewPipe 内置服务 ID：0 为 YouTube。 */
        const val YOUTUBE_SERVICE_ID = 0
    }
}
